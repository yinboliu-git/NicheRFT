#!/usr/bin/env python3
"""Rerun Stage I--III independently for each seed, with fixed cell partitions.

This producer creates new results; it does not assert that old paper scores were
generated by this code. Existing outputs are rejected rather than silently reused.
"""
import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from core_modules.paper_protocol import PAPER_K, PAPER_SEEDS, PAPER_SWEEP, stage12_command, flow_command


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--dataset", choices=list(PAPER_K), required=True)
    p.add_argument("--data_path", required=True)
    p.add_argument("--output_dir", required=True)
    p.add_argument("--split_manifest", help="Optional authoritative partition by actual cell IDs")
    p.add_argument("--split_seed", type=int, default=42)
    p.add_argument("--fold", type=int, default=0)
    p.add_argument("--seeds", type=int, nargs="+", default=list(PAPER_SEEDS))
    p.add_argument("--device", default="cuda")
    p.add_argument("--controls", action="store_true", help="Matched residual and calibration/flow factorial")
    p.add_argument("--solver_sweep", action="store_true")
    p.add_argument("--dry_run", action="store_true")
    a = p.parse_args()
    if len(a.seeds) < 2 or len(set(a.seeds)) != len(a.seeds):
        p.error("At least two distinct seeds required; paper uses 42--46")
    out = Path(a.output_dir).resolve()
    data = Path(a.data_path).resolve()
    manifest = Path(a.split_manifest).resolve() if a.split_manifest else None
    commands = []
    for seed in a.seeds:
        cache = out / "caches" / a.dataset / f"seed{seed}"
        commands.append(stage12_command(sys.executable, a.dataset, data, cache, seed,
            fold=a.fold, split_seed=a.split_seed, split_manifest=manifest, flags=["--device", a.device]))
        variants = [("full", "flow", [])]
        if a.controls:
            variants += [("residual", "residual", []), ("flow_without_calibration", "flow", ["--de_shrink_strength", "0"])]
        for name, objective, flags in variants:
            commands.append(flow_command(sys.executable, a.dataset, cache,
                out / "runs" / name / a.dataset, seed, fold=a.fold, objective=objective,
                sweep=PAPER_SWEEP if a.solver_sweep and name == "full" else (8,),
                flags=["--device", a.device, *flags]))
    for cmd in commands:
        print("COMMAND:", " ".join(cmd), flush=True)
    if a.dry_run:
        return
    if out.exists() and any(out.iterdir()):
        raise FileExistsError("Use a new empty output directory; old artifacts will not be relabeled")
    out.mkdir(parents=True, exist_ok=True)
    canonical_fingerprint = None
    for seed in a.seeds:
        seed_cmds = [c for c in commands if c[c.index("--seed") + 1] == str(seed)]
        subprocess.run(seed_cmds[0], cwd=ROOT, check=True)
        from core_modules.evaluation import context_for_fold
        cache = out / "caches" / a.dataset / f"seed{seed}"
        context = context_for_fold(cache / f"fold{a.fold}")
        if canonical_fingerprint is None:
            canonical_fingerprint = context.fingerprint
        elif canonical_fingerprint != context.fingerprint:
            raise ValueError("Training seeds changed the evaluation membership, target panel or kernel")
        for cmd in seed_cmds[1:]:
            subprocess.run(cmd, cwd=ROOT, check=True)
    for name in (["full", "residual", "flow_without_calibration"] if a.controls else ["full"]):
        subprocess.run([sys.executable, "experiments/eval_multiseed.py",
            "--cache_root", str(out / "caches"), "--cache_layout", "per_seed",
            "--runs_root", str(out / "runs" / name), "--datasets", a.dataset,
            "--fold", str(a.fold), "--seeds", *map(str, a.seeds)], cwd=ROOT, check=True)
    for prediction in ("retrieval_pred_test.npz", "calibrated_prior_pred_test.npz"):
        subprocess.run([sys.executable, "experiments/eval_multiseed.py",
            "--cache_root", str(out / "caches"), "--cache_layout", "per_seed",
            "--runs_root", str(out / "runs" / "full"), "--datasets", a.dataset,
            "--fold", str(a.fold), "--seeds", *map(str, a.seeds), "--prediction", prediction,
            "--output", str(out / (prediction.removesuffix(".npz") + "_summary.json"))], cwd=ROOT, check=True)


if __name__ == "__main__":
    main()
